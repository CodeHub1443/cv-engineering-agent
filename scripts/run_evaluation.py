def _generate_coco_val_yaml(yaml_path: Path) -> None:
    """Write a minimal COCO val-only yaml with absolute paths."""
    names_lines = "\n".join(f"  {k}: {v}" for k, v in COCO_NAMES.items())
    yaml_content = f"""\
# COCO val2017 evaluation yaml — generated by scripts/run_evaluation.py (D-061)
# Dataset: Microsoft COCO 2017 val split (5000 images, CC BY 4.0)
# Why absolute path: avoids YOLO auto-download; only val split is available locally.
# train key required by ultralytics check_det_dataset; points to val list since
# no training is performed — this is an eval-only run.
path: {COCO_ROOT}
train: val2017.txt
val: val2017.txt
names:
{names_lines}
"""
    yaml_path.write_text(yaml_content)


def _poll_vram(accum: list[int], stop: threading.Event, interval: float = 2.0) -> None:
    """Daemon thread: poll nvidia-smi for used VRAM every `interval` seconds."""
    while not stop.is_set():
        try:
            out = subprocess.check_output(
                ["nvidia-smi", "--query-gpu=memory.used", "--format=csv,noheader,nounits"],
                timeout=5.0,
            ).decode().strip()
            for line in out.splitlines():
                try:
                    accum.append(int(line.strip()))
                except ValueError:
                    pass
        except (subprocess.SubprocessError, FileNotFoundError):
            pass
        stop.wait(timeout=interval)


